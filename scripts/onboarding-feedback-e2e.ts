import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { AddressInfo } from "node:net";
import { serve } from "@hono/node-server";
import { createServer } from "vite";
import { chromium } from "playwright-core";
import { receiverFixture } from "../feedback-service/test-support";
import { setup, fakeProvider, TOKEN } from "../sidecar/server/test-app";
import { openStore } from "../sidecar/store/store";
import { resolveChromiumExecutable } from "../sidecar/applications/launch";

const dir = mkdtempSync(join(tmpdir(), "heel-onboarding-feedback-"));
const receiver = receiverFixture();
const remote = serve({ fetch: request => receiver.app.fetch(request, receiver.env), hostname: "127.0.0.1", port: 0 });
await new Promise<void>(resolve => remote.listening ? resolve() : remote.once("listening", resolve));
const endpoint = `http://127.0.0.1:${(remote.address() as AddressInfo).port}/reports`;
process.env.VITE_FEEDBACK_ENDPOINT = endpoint;
const vite = await createServer({ plugins: [{ name: "crash-proof", configureServer(server) {
  server.middlewares.use("/__crash-proof", async (_req, res) => {
    res.setHeader("Content-Type", "text/html");
    res.end(await server.transformIndexHtml("/__crash-proof", '<div id="root"></div><script type="module" src="/scripts/fixtures/crash-report.tsx"></script>'));
  });
} }], server: { host: "localhost", port: 1420, strictPort: true, hmr: false, watch: { ignored: ["**/*"] } }, clearScreen: false });
await vite.listen();
const database = join(dir, "heel.db");
let test = setup({ codex: fakeProvider("codex") }, {}, undefined, openStore({ path: database }), { dataDir: dir });
const helper = serve({ fetch: request => test.app.fetch(request), hostname: "127.0.0.1", port: 0 });
await new Promise<void>(resolve => helper.listening ? resolve() : helper.once("listening", resolve));
const browser = await chromium.launch({ headless: true, executablePath: resolveChromiumExecutable(chromium) });
const page = await browser.newPage({ viewport: { width: 300, height: 420 } });
page.setDefaultTimeout(12_000);
const url = `http://localhost:1420/?window=panel&sidecar=${(helper.address() as AddressInfo).port}:${TOKEN}`;
const checks: string[] = [];
try {
  await page.goto(url);
  await page.getByLabel("Your first task", { exact: true }).fill("Synthetic reminder PRIVATE-TASK-MARKER");
  await page.getByRole("button", { name: "Add task", exact: true }).click();
  await page.getByRole("heading", { name: "Choose your AI", exact: true }).waitFor();
  assert.equal(test.store.tasks.list().length, 1);
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByRole("button", { name: "Start using Heel", exact: true }).click();
  await page.locator('.layer[aria-label="Set up Heel"]').waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "Job applications", exact: true }).waitFor();
  assert.equal(test.store.onboarding.get().step, 3);
  checks.push("First run created one real task and reached Today through three skippable steps");
  test.store.close();
  test = setup({ codex: fakeProvider("codex") }, {}, undefined, openStore({ path: database }), { dataDir: dir });
  await page.reload();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("heading", { name: "Help", exact: true }).click();
  await page.getByRole("button", { name: "Set up Heel again", exact: true }).click();
  await page.getByRole("button", { name: "Skip setup", exact: true }).click();
  await page.locator('.layer[aria-label="Set up Heel"]').waitFor({ state: "hidden" });
  await page.getByRole("button", { name: "Job applications", exact: true }).waitFor();
  assert.equal(test.store.tasks.list().length, 1);
  checks.push("SQLite reopen retained dismissal; Help replay and skip did not duplicate the task");
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("heading", { name: "About", exact: true }).click();
  await page.getByRole("button", { name: "Send feedback", exact: true }).click();
  await page.getByLabel("In one line", { exact: true }).fill("Synthetic feedback from the app");
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Send feedback", exact: true }).waitFor();
  await page.getByRole("button", { name: "Send feedback", exact: true }).click();
  assert.equal(await page.getByLabel("In one line", { exact: true }).inputValue(), "Synthetic feedback from the app");
  await page.getByLabel("What happened", { exact: true }).fill("Testing in-app delivery and safe retries.");
  await page.evaluate(() => localStorage.setItem("heel:debug-log", JSON.stringify([{ at: Date.now(), level: "error", where: "panel", text: "PRIVATE-CV-MARKER raw error" }])));
  let loseReply = true;
  await page.route(endpoint, async route => {
    const response = await route.fetch();
    if (route.request().method() === "POST" && loseReply) { loseReply = false; await route.abort("failed"); }
    else await route.fulfill({ response });
  });
  await page.getByRole("switch", { name: "Include recent app events", exact: true }).click();
  await page.getByRole("button", { name: "Preview debug details", exact: true }).click();
  await page.getByRole("button", { name: "Send report", exact: true }).click();
  await page.getByText("Could not confirm delivery.", { exact: false }).waitFor();
  assert.equal(receiver.messages.length, 1);
  await page.reload();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("heading", { name: "About", exact: true }).click();
  await page.getByRole("button", { name: "Send feedback", exact: true }).click();
  assert.equal(await page.getByLabel("In one line", { exact: true }).inputValue(), "Synthetic feedback from the app");
  await page.getByRole("button", { name: "Retry report", exact: true }).click();
  await page.getByText("Report received. Reference:", { exact: false }).waitFor();
  assert.equal(receiver.messages.length, 1);
  const rows = receiver.db.prepare("SELECT payload FROM reports").all();
  assert.equal(rows.length, 1);
  const payload = String(rows[0]!.payload);
  assert.doesNotMatch(payload, /PRIVATE-TASK-MARKER|PRIVATE-CV-MARKER|dataDir|sidecarLog/);
  checks.push("Direct report received; lost response and restart preserved draft; retry produced one stored report and one notification");
  checks.push("Diagnostic payload excluded task text, raw errors, CV marker, paths and helper logs");
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: join(dir, "report-received.png"), fullPage: true });
  writeFileSync(join(dir, "proof.json"), JSON.stringify({ date: new Date().toISOString(), checks, report: JSON.parse(payload), notifications: receiver.messages.length, evidenceDir: dir }, null, 2));
  await page.getByRole("button", { name: "Close report", exact: true }).click();
  await page.evaluate(() => { setTimeout(() => { throw new Error("PRIVATE-BACKGROUND-MARKER"); }, 0); });
  await page.getByRole("button", { name: "Report", exact: true }).click();
  await page.getByRole("switch", { name: /Include diagnostic facts/ }).click();
  await page.getByRole("button", { name: "Review crash report", exact: true }).click();
  await page.getByRole("button", { name: "Send crash report", exact: true }).click();
  await page.getByText("Report received. Reference:", { exact: false }).waitFor();
  assert.equal(receiver.messages.length, 2);
  const omitted = receiver.db.prepare("SELECT payload FROM reports WHERE json_extract(payload, '$.kind') = 'crash'").get()!;
  assert.equal(JSON.parse(String(omitted.payload)).diagnostics, null);
  checks.push("Actual uncaught background error offered a report popup; opting out sent no diagnostic facts or logs");
  await page.goto(url.replace("/?window=panel", "/__crash-proof?window=panel"));
  await page.getByRole("button", { name: "Report a crash", exact: true }).click();
  await page.getByRole("button", { name: "Review crash report", exact: true }).click();
  await page.getByRole("button", { name: "Send crash report", exact: true }).click();
  await page.getByText("Report received. Reference:", { exact: false }).waitFor();
  assert.equal(receiver.messages.length, 3);
  const crash = receiver.db.prepare("SELECT payload FROM reports WHERE json_extract(payload, '$.diagnostics.crashed') = 1").get()!;
  assert.doesNotMatch(String(crash.payload), /PRIVATE-CRASH-MARKER/);
  assert.equal(JSON.parse(String(crash.payload)).diagnostics.crashed, true);
  assert.equal(JSON.parse(String(crash.payload)).diagnostics.events.length, 0);
  checks.push("Actual React render failure exposed direct crash reporting, received once without transmitting the raw exception");
  await page.screenshot({ path: join(dir, "crash-received.png"), fullPage: true });
  writeFileSync(join(dir, "proof.json"), JSON.stringify({ date: new Date().toISOString(), checks, notifications: receiver.messages.length, evidenceDir: dir }, null, 2));
  console.log(JSON.stringify({ ok: true, checks, evidenceDir: dir }, null, 2));
} catch (error) {
  await page.screenshot({ path: join(dir, "failure.png"), fullPage: true }).catch(() => {});
  console.error(`Synthetic UI evidence: ${dir}`); throw error;
} finally {
  await browser.close(); await vite.close();
  for (const server of [helper, remote]) { server.closeAllConnections(); await new Promise<void>(resolve => server.close(() => resolve())); }
  test.store.close(); receiver.db.close();
}
